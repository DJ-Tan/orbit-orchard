const pe = (t, id, x, y) => H[t]({ pointerId: id, clientX: x, clientY: y, button: 0, preventDefault() {} });
const w = E.W[0], l = w.levels[0];
O.loadLevel(l, { world: w, mode: "journey" }); D.advance(150);
const out = [];
